def A(txt, w=None):
    rows = [r.strip() for r in txt.strip('\n').split('\n')]
    rows = [r for r in rows if r]
    if w is None: w = max(len(r) for r in rows)
    out = [r.ljust(w, '.') for r in rows]
    assert all(len(r) == w for r in out), [len(r) for r in out]
    assert w % 8 == 0 and len(out) % 8 == 0, (w, len(out))
    return out

def mirror(rows): return [r[::-1] for r in rows]

def shift(rows, n):
    return [r[-n:] + r[:-n] for r in rows]

def overlay(base, pts):
    g = [list(r) for r in base]
    for x, y in pts:
        if 0 <= y < len(g) and 0 <= x < len(g[0]): g[y][x] = '#'
    return [''.join(r) for r in g]

def clear(base, pts):
    g = [list(r) for r in base]
    for x, y in pts:
        if 0 <= y < len(g) and 0 <= x < len(g[0]): g[y][x] = '.'
    return [''.join(r) for r in g]

def line(x0, y0, x1, y1):
    pts = []; n = max(abs(x1 - x0), abs(y1 - y0))
    for i in range(n + 1):
        pts.append((round(x0 + (x1 - x0) * i / max(n, 1)), round(y0 + (y1 - y0) * i / max(n, 1))))
    return pts


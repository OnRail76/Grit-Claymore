def helmet(frames, view):
    """Soldado enemigo: casco redondo con visera en lugar de la boina de Grit."""
    out = []
    for f in frames:
        g = [list(r) for r in f]
        if view == 'front':
            h = ['................', '.....######.....', '....########....', '...##########...', '.....#.##.#.....', '......####......']
        elif view == 'back':
            h = ['................', '.....######.....', '....########....', '...##########...', '.....######.....', '......####......']
        elif view == 'left':
            h = ['................', '......#####.....', '.....#######....', '....#########...', '......#.###.....', '.......###......']
        else:
            h = [r[::-1] for r in ['................', '......#####.....', '.....#######....', '....#########...', '......#.###.....', '.......###......']]
        for y in range(6): g[y] = list(h[y])
        out.append([''.join(r) for r in g])
    return out

def rifle(direction):
    """Fusil en 8 direcciones: 0 arriba, 1 abajo, 2 izq, 3 dcha, 4-7 diagonales."""
    L = {
     0: line(12, 0, 12, 8) + line(13, 2, 13, 6),
     1: line(12, 8, 12, 15) + line(13, 9, 13, 13),
     2: line(0, 8, 6, 8) + line(1, 9, 5, 9),
     3: line(9, 8, 15, 8) + line(10, 9, 14, 9),
     4: line(1, 1, 6, 6) + line(2, 1, 7, 6),
     5: line(14, 1, 9, 6) + line(13, 1, 8, 6),
     6: line(5, 9, 1, 13) + line(4, 9, 0, 13),
     7: line(10, 9, 14, 13) + line(11, 9, 15, 13),
    }
    return L[direction]

BODY_FOR_DIR = {0: 'back', 1: 'front', 2: 'left', 3: 'right', 4: 'back', 5: 'back', 6: 'front', 7: 'front'}
GRIT_BODIES = {'front': GRIT_FRONT, 'back': GRIT_BACK, 'left': GRIT_LEFT, 'right': GRIT_RIGHT}

def grit(direction, f):
    return overlay(GRIT_BODIES[BODY_FOR_DIR[direction]][f], rifle(direction))

def soldier(direction, f):
    view = BODY_FOR_DIR[direction]
    body = helmet(GRIT_BODIES[view], view)[f]
    return overlay(body, rifle(direction))

